/*
 * Host check for the wake-up access code and payload maths.
 *
 * The reference (/shared/github.com-608-NS1-Wakeup-Demo, docs/
 * wakeup-protocol.en.md) publishes four worked examples.  This reproduces
 * them from the port in src/wake/ so a change to the maths cannot drift from
 * the values a working implementation produces.  It is a host binary: it
 * never touches the pad.
 *
 *     make wake-vectors
 *
 * Note the trap in the reference's table: its fourth column is the *wake-up*
 * access code, i.e. the standard sync word with the lower 32 bits already
 * inverted.  The upper 32 bits are the standard ones, so reading that column
 * as a normal access code looks plausible and is wrong.
 *
 * Address order: the reference writes an address the way it is printed
 * (aa:bb:cc:dd:ee:ff); this firmware stores addresses least significant byte
 * first, which is that string reversed.  The table below is written in the
 * printed form and reversed on the way in, so a reader can compare it with
 * the reference line by line.
 */

#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "wake_payload.h"
#include "wakeup_code.h"

struct vector {
    const char *printed;      /* the reference's own spelling */
    const char *access_code;  /* 72 bits: preamble, 16 hex of sync word, trailer */
    uint32_t wake32;          /* the reference's W */
    uint8_t code[4];          /* the reference's 4-byte wake-up code */
};

static const struct vector vectors[] = {
    {"55:55:55:55:55:55", "AB155555579F98210A", 0x79F98210u, {0x10, 0x82, 0xf9, 0x79}},
    {"aa:aa:aa:aa:aa:aa", "54EAAAAA9FAD696895", 0xfad69689u, {0x89, 0x96, 0xd6, 0xfa}},
    {"54:f7:08:90:34:25", "54E40D0940CB13E3F5", 0x0cb13e3fu, {0x3f, 0x3e, 0xb1, 0x0c}},
    {"ef:4a:c5:1a:00:ee", "AB06803B9AF3BC02D5", 0xaf3bc02du, {0x2d, 0xc0, 0x3b, 0xaf}},
};

static unsigned failures;

static void check(int condition, const char *what, const char *printed)
{
    if (!condition) {
        printf("FAIL %s for %s\n", what, printed);
        failures++;
    }
}

/* "aa:bb:cc:dd:ee:ff" -> {ff, ee, dd, cc, bb, aa}. */
static int parse_printed(const char *text, uint8_t address[6])
{
    unsigned i;

    for (i = 0; i < 6U; ++i) {
        unsigned value;

        if (sscanf(text + i * 3U, "%2x", &value) != 1) return -1;
        address[5U - i] = (uint8_t)value;
        if (i < 5U && text[i * 3U + 2U] != ':') return -1;
    }
    return 0;
}

int main(void)
{
    unsigned i;

    for (i = 0; i < sizeof(vectors) / sizeof(vectors[0]); ++i) {
        const struct vector *vector = &vectors[i];
        uint8_t address[6];
        uint8_t parity[5];
        uint8_t code[4];
        char access[17];
        uint64_t sync;
        uint32_t wake32;

        printf("%s\n", vector->printed);
        if (parse_printed(vector->printed, address) != 0) {
            printf("FAIL could not parse\n");
            failures++;
            continue;
        }

        sync = wake_sync_word(address);
        wake32 = (uint32_t)~sync;
        check(wake32 == vector->wake32, "W", vector->printed);

        wake_code(address, code);
        check(memcmp(code, vector->code, 4U) == 0, "wake-up code", vector->printed);

        /* The parity the baseband is given is the inverted one, and its four
         * low bytes are the wake-up code in transmission order. */
        wake_parity_inverted(address, parity);
        check(memcmp(parity, vector->code, 4U) == 0,
              "inverted parity low bytes", vector->printed);

        /* The reference's fourth column is the 72-bit wake-up access code:
         * a 4-bit preamble, the 64-bit wake-up sync word, a 4-bit trailer.
         * The middle 16 hex digits are the sync word, and the claim under
         * test is that its upper 32 bits are the standard ones while its
         * lower 32 are inverted.  The preamble and trailer are generated by
         * the baseband from the parity field and are not reproduced here -
         * the four published values disagree about them, and nothing in this
         * port computes them. */
        snprintf(access, sizeof(access), "%016llX",
                 (unsigned long long)(sync ^ UINT64_C(0xFFFFFFFF)));
        check(strncmp(access, vector->access_code + 1, 16U) == 0,
              "wake-up sync word inside the access code", vector->printed);

        printf("  W=%08X code=%02X %02X %02X %02X access=%s\n", wake32,
               code[0], code[1], code[2], code[3], vector->access_code);
    }

    /* Whitening sanity: cancelling a sequence out has to be its own inverse,
     * and the phase-1 body has to be the four-byte pattern repeated. */
    {
        uint8_t body[WAKE_BODY_MAX];
        uint8_t again[WAKE_BODY_MAX];
        uint8_t address[6];
        unsigned j;

        if (parse_printed(vectors[2].printed, address) == 0) {
            wake_build_phase1(address, body, WAKE_BODY_MAX);
            memcpy(again, body, sizeof(again));
            wake_whiten_cancel(again, WAKE_BODY_MAX, 0x69, WAKE_WHITEN_SKIP_MULTISLOT);
            wake_whiten_cancel(again, WAKE_BODY_MAX, 0x69, WAKE_WHITEN_SKIP_MULTISLOT);
            check(memcmp(body, again, sizeof(body)) == 0,
                  "whitening cancel is an involution", vectors[2].printed);

            for (j = 0; j < 300U; ++j) {
                if (body[j] != body[j % 4U]) {
                    check(0, "phase 1 body repeats every 4 bytes",
                          vectors[2].printed);
                    break;
                }
            }
        }
    }

    if (failures) {
        printf("%u check(s) failed\n", failures);
        return 1;
    }
    printf("wake vectors OK\n");
    return 0;
}
