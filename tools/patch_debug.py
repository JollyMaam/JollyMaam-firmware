#!/usr/bin/env python3
"""Build a copy of the SDK's ``debug.c`` that prints to the USB console.

The vendor ``debug.c`` compiles ``printf``, ``puts``, ``put_buf`` and
``log_print`` into empty stubs whenever ``CONFIG_DEBUG_ENABLE`` is undefined,
which this application deliberately leaves off.  That makes the controller
library's LMP/HCI tracing unreachable: the library calls ``log_print`` and the
call goes nowhere.

This script emits a replacement translation unit whose stubs forward to
``cyclone2_usb_debug()``, so ``make DEBUG_LOG=1`` can show what the Bluetooth
controller is doing below the stack's own HCI event delivery.  ``putchar`` and
``log_putbyte`` stay silent: the sleep callbacks call ``putchar`` from contexts
where a USB transfer is not safe.

The SDK tree is never modified; the Makefile compiles the generated file in
place of the vendor one.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Names the generated file must define, so a vendor change is caught here
# rather than as a link error.
REQUIRED = (
    "int putchar(int a)",
    "int puts(const char *out)",
    "int printf(const char *format, ...)",
    "void put_buf(const u8 *buf, int len)",
    "void put_u8hex(u8 dat)",
    "void put_u16hex(u16 dat)",
    "void put_u32hex(u32 dat)",
    "void log_print(int level, const char *tag, const char *format, ...)",
    "int assert_printf(const char *format, ...)",
)

GENERATED = r'''/*
 * GENERATED by tools/patch_debug.py - do not edit.
 *
 * A build copy of apps/common/debug/debug.c whose stubs forward the
 * controller library's log output to the USB console.
 */
#include "app_config.h"
#include "typedef.h"
#include <stdarg.h>
#include "usb.h"

#ifndef CONFIG_DEBUG_ENABLE

int putchar(int a)
{
    /* Called from the sleep callbacks; never touch USB from there. */
    return a;
}

int puts(const char *out)
{
    cyclone2_usb_debug("SDK: %s", out ? out : "");
    return 0;
}

int printf(const char *format, ...)
{
    char text[128];
    va_list arguments;

    va_start(arguments, format);
    vsnprintf(text, sizeof(text), format, arguments);
    va_end(arguments);
    cyclone2_usb_debug("SDK: %s", text);
    return 0;
}

void put_buf(const u8 *buf, int len)
{
    char line[80];
    int offset;

    if (!buf || len <= 0) return;
    for (offset = 0; offset < len; offset += 16) {
        int used = snprintf(line, sizeof(line), "SDK buf:");
        int index;

        for (index = 0; index < 16 && offset + index < len; index++)
            used += snprintf(line + used, sizeof(line) - (size_t)used,
                             " %02x", buf[offset + index]);
        cyclone2_usb_debug("%s", line);
    }
}

void put_u8hex(u8 dat)
{
    cyclone2_usb_debug("SDK: %02x", dat);
}

void put_u16hex(u16 dat)
{
    cyclone2_usb_debug("SDK: %04x", dat);
}

void put_u32hex(u32 dat)
{
    cyclone2_usb_debug("SDK: %08x", dat);
}

void log_print(int level, const char *tag, const char *format, ...)
{
    char text[128];
    va_list arguments;

    (void)level;
    va_start(arguments, format);
    vsnprintf(text, sizeof(text), format, arguments);
    va_end(arguments);
    cyclone2_usb_debug("%s%s", tag ? tag : "", text);
}

#ifndef CONFIG_DEBUG_LITE_ENABLE
void log_putbyte(char c)
{
    (void)c;
}
#endif /* #ifndef CONFIG_DEBUG_LITE_ENABLE */

int assert_printf(const char *format, ...)
{
    cpu_assert_debug();
    return 0;
}

#endif /* #ifndef CONFIG_DEBUG_ENABLE */
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()

    vendor = args.source.read_text()
    missing = [name for name in REQUIRED if name not in vendor]
    if missing:
        print(f"patch_debug: {args.source} no longer defines "
              f"{', '.join(missing)}; update tools/patch_debug.py",
              file=sys.stderr)
        return 1

    args.destination.write_text(GENERATED)
    return 0


if __name__ == "__main__":
    sys.exit(main())
