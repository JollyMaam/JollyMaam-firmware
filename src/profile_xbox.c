    p.hat = HAT_RIGHT;
    p.buttons = PAD_A | PAD_SELECT | PAD_HOME;
    CHECK(report(&p, 0, out, &id) == STATE_SIZE && id == REPORT_STATE);
    CHECK(out[0] == 0x00 && out[1] == 0x80 && out[12] == 3 && out[13] == 1 && out[15] == 1);
