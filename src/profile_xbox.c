#define X360_SIZE 20

static struct {
    u8 series;
    u8 usb;
    u8 players;
    u8 last[X360_SIZE];          /* the last state sent, either layout */
    u8 sent;
    u8 guide;
    u32 sent_ms;
    u8 rumble[2];
    u8 rumble_timed;
    u32 rumble_until;
    u8 er[16], ir[16];
} xb;

static void state(u8 *s, const struct pad *p)
{
    u16 b = p->buttons;

    memset(s, 0, STATE_SIZE);
    /* Series X|S: Share is its own bit, where the capture button goes. */
    if (xb.series && (b & PAD_SCREENSHOT)) {
        b &= (u16)~PAD_SCREENSHOT;
        s[15] = 0x01;
    }
    util_put16(s + 0, (u16)(p->lx + 32768));
    util_put16(s + 2, (u16)(p->ly + 32768));
    util_put16(s + 4, (u16)(p->rx + 32768));
    util_put16(s + 6, (u16)(p->ry + 32768));
    util_put16(s + 8, (u16)(p->l2 >> 6));
    util_put16(s + 10, (u16)(p->r2 >> 6));
    s[12] = p->hat < HAT_NEUTRAL ? (u8)(p->hat + 1) : 0;
    s[13] = (u8)b;
    s[14] = (u8)((b >> 8) & 0x7f);
    if (!xb.series && (b & PAD_SELECT)) s[15] = 0x01;
}

static u8 magnitude(u8 v)
{
    return v >= 100 ? 255 : (u8)(v * 255u / 100);
}

/* Motor bits, two magnitudes in percent, a duration in 10 ms, a loop count:
 * a looping effect runs until the host changes it (SDL always loops). */
static void rumble(const u8 *d, u32 now)
{
    u32 ms = d[5] * 10u;

    xb.rumble[0] = (d[0] & 0x02) ? magnitude(d[3]) : 0;
    xb.rumble[1] = (d[0] & 0x01) ? magnitude(d[4]) : 0;
    xb.rumble_timed = !d[7] && ms;
    xb.rumble_until = now + (ms > RUMBLE_MAX_MS ? RUMBLE_MAX_MS : ms);
}

static void host(u32 now, struct profile_host *h)
{
    int on = !xb.rumble_timed || (s32)(now - xb.rumble_until) < 0;

    h->rumble[0] = on ? xb.rumble[0] : 0;
    h->rumble[1] = on ? xb.rumble[1] : 0;
    h->has_players = xb.usb;
    h->players = xb.players;
}

static u8 begin(const struct profile_session *s)
{
    static const u8 firmware_key[16] = { 'C', 'Y', 'C', 'L', 'O', 'N', 'E', '2',
                                         '-', 'X', 'B', 'O', 'X', 'B', 'L', 'E' };
    u8 block[16];
    u8 series = xb.series;

    memset(&xb, 0, sizeof(xb));
    xb.series = series;
    xb.usb = s->usb;
    /* LE security keys for this slot: AES of the slot's address under a
     * fixed key.  Not secret from someone with this firmware, which is as
     * much as a gamepad's bond needs. */
    memset(block, 0, sizeof(block));
    memcpy(block, s->address, 6);
    block[6] = s->slot;
    block[15] = 'E';
    util_aes128(firmware_key, block, xb.er);
    block[15] = 'I';
    util_aes128(firmware_key, block, xb.ir);
    return IMU_OFF;
}

static u8 begin_classic(const struct profile_session *s)
{
    xb.series = 0;
    return begin(s);
}

static u8 begin_ble(const struct profile_session *s)
{
    xb.series = 1;
    return begin(s);
}

static s16 up(s16 v)
{
    return v == -32768 ? 32767 : (s16)-v;
}

/* The wired Xbox 360 report: 0x00, its size, buttons, triggers, sticks with
 * y up. */
static int x360_report(const struct pad *p, u32 now, u8 *out, u8 *id)
{
    static const u8 hat_bits[HAT_NEUTRAL] = { 0x01, 0x09, 0x08, 0x0a, 0x02, 0x06, 0x04, 0x05 };
    u16 b = p->buttons;

    memset(out, 0, X360_SIZE);
    out[1] = X360_SIZE;
    out[2] = (u8)((p->hat < HAT_NEUTRAL ? hat_bits[p->hat] : 0) | (b & PAD_START ? 0x10 : 0) |
                  (b & PAD_SELECT ? 0x20 : 0) | (b & PAD_L3 ? 0x40 : 0) | (b & PAD_R3 ? 0x80 : 0));
    out[3] = (u8)((b & PAD_L1 ? 0x01 : 0) | (b & PAD_R1 ? 0x02 : 0) | (b & PAD_HOME ? 0x04 : 0) |
                  (b & PAD_A ? 0x10 : 0) | (b & PAD_B ? 0x20 : 0) | (b & PAD_X ? 0x40 : 0) |
                  (b & PAD_Y ? 0x80 : 0));
    out[4] = (u8)(p->l2 >> 8);
    out[5] = (u8)(p->r2 >> 8);
    util_put16(out + 6, (u16)p->lx);
    util_put16(out + 8, (u16)up(p->ly));
    util_put16(out + 10, (u16)p->rx);
    util_put16(out + 12, (u16)up(p->ry));
    if (xb.sent && !memcmp(out, xb.last, X360_SIZE) && now - xb.sent_ms < KEEPALIVE_MS) return 0;
    memcpy(xb.last, out, X360_SIZE);
    xb.sent = 1;
    xb.sent_ms = now;
    *id = 0;
    return X360_SIZE;
}

/* Rumble (00 08 00 big small) and the ring of lights (01 03 n): n 2-5 and
 * 6-9 are players 1-4. */
static void x360_write(const struct bt_write *w)
{
    static const u8 nintendo[] = { 0x1, 0x3, 0x7, 0xf };

    if (w->len >= 5 && w->data[0] == 0x00 && w->data[1] == 0x08) {
        xb.rumble[0] = w->data[3];
        xb.rumble[1] = w->data[4];
        xb.rumble_timed = 0;
    } else if (w->len >= 3 && w->data[0] == 0x01 && w->data[1] == 0x03) {
        u8 n = w->data[2];

        xb.players = n >= 2 && n <= 5 ? nintendo[n - 2] : n >= 6 && n <= 9 ? nintendo[n - 6] : 0;
    }
}

/* State on change, and every 100 ms unchanged so an idle link keeps moving;
 * Guide as its own report when it changes, which must not be lost. */
static int report(const struct pad *p, u32 now, u8 *out, u8 *id)
{
    u8 guide = (p->buttons & PAD_HOME) != 0;

    if (xb.usb) return x360_report(p, now, out, id);
    if (!xb.series && guide != xb.guide && host_send(REPORT_GUIDE, &guide, 1)) xb.guide = guide;
    state(out, p);
    if (xb.sent && !memcmp(out, xb.last, STATE_SIZE) &&
        (xb.series || now - xb.sent_ms < KEEPALIVE_MS))
        return 0;
    memcpy(xb.last, out, STATE_SIZE);
    xb.sent = 1;
    xb.sent_ms = now;
    *id = REPORT_STATE;
    return STATE_SIZE;
}

static int write(const struct bt_write *w, u32 now, struct bt_bond *bond)
{
    (void)bond;
    if (xb.usb) {
        if (w->kind == BT_WRITE_OUTPUT) x360_write(w);
        return 0;
    }
    if ((w->kind == BT_WRITE_OUTPUT && w->id == REPORT_RUMBLE && w->len >= 8) ||
        (w->kind == BT_WRITE_ATT && w->id == BLE_OUTPUT && w->len >= 8))
        rumble(w->data, now);
    return 0;
}

static int read(u8 kind, u16 id, u16 offset, u8 *out, u16 max)
{
    (void)offset;
    if (kind != BT_WRITE_ATT || max < 8) return -1;
    if (id == BLE_BATTERY) {
        out[0] = 100;
        return 1;
    }
    if (id == BLE_OUTPUT) {
        memset(out, 0, 8);
        return 8;
    }
    return -1;
}

static u8 advertising(const struct bt_bond *bond, int pairing, int wake, u8 out[31])
{
    static const u8 adv[] = { 0x02, 0x01, 0x06, 0x03, 0x19, 0xc4, 0x03, 0x03, 0x03, 0x12, 0x18 };

    (void)bond;
    (void)wake;
    memcpy(out, adv, sizeof(adv));
    out[2] = pairing ? 0x06 : 0x04;    /* general discoverable only when pairing */
    return sizeof(adv);
}

