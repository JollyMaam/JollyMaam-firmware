/* LMP PDU opcodes (Bluetooth Core, Vol 2 Part C, 5.1) for owned link
 * manager code.  The SDK passes received PDUs as opcode0 = opcode << 1 (the
 * PDU's first byte without its transaction ID); PDU() gives that value.
 * After LMP_accepted / LMP_not_accepted, opcode1 is the answered opcode,
 * also shifted; after an escape-4 PDU it is the extended opcode, unshifted. */
#ifndef BTCTRLER_LMP_PDU_H
#define BTCTRLER_LMP_PDU_H

#define PDU(opcode) ((opcode) << 1)

enum {
    NAME_REQ = 1, NAME_RES, ACCEPTED, NOT_ACCEPTED, CLKOFFSET_REQ, CLKOFFSET_RES, DETACH,
    IN_RAND, COMB_KEY, UNIT_KEY, AU_RAND, SRES, TEMP_RAND, TEMP_KEY, ENCRYPTION_MODE_REQ,
    ENCRYPTION_KEY_SIZE_REQ, START_ENCRYPTION_REQ, STOP_ENCRYPTION_REQ, SWITCH_REQ,
    HOLD, HOLD_REQ, SNIFF_REQ = 23, UNSNIFF_REQ, INCR_POWER_REQ = 31, DECR_POWER_REQ,
    MAX_POWER, MIN_POWER, AUTO_RATE, PREFERRED_RATE, VERSION_REQ, VERSION_RES, FEATURES_REQ,
    FEATURES_RES, QUALITY_OF_SERVICE, QUALITY_OF_SERVICE_REQ, SCO_LINK_REQ,
    REMOVE_SCO_LINK_REQ, MAX_SLOT, MAX_SLOT_REQ, TIMING_ACCURACY_REQ, TIMING_ACCURACY_RES,
    SETUP_COMPLETE, USE_SEMI_PERMANENT_KEY, HOST_CONNECTION_REQ, SLOT_OFFSET,
    PAGE_MODE_REQ, PAGE_SCAN_MODE_REQ, SUPERVISION_TIMEOUT, TEST_ACTIVATE, TEST_CONTROL,
    ENCRYPTION_KEY_SIZE_MASK_REQ, ENCRYPTION_KEY_SIZE_MASK_RES, SET_AFH,
    ENCAPSULATED_HEADER, ENCAPSULATED_PAYLOAD, SIMPLE_PAIRING_CONFIRM,
    SIMPLE_PAIRING_NUMBER, DHKEY_CHECK, ESCAPE_3 = 126, ESCAPE_4 = 127,
};

/* Escape 4 extended opcodes. */
enum {
    ACCEPTED_EXT = 1, NOT_ACCEPTED_EXT, FEATURES_REQ_EXT, FEATURES_RES_EXT,
    PACKET_TYPE_TABLE_REQ = 11, ESCO_LINK_REQ, REMOVE_ESCO_LINK_REQ,
    CHANNEL_CLASSIFICATION_REQ = 16, CHANNEL_CLASSIFICATION, SNIFF_SUBRATING_REQ = 21,
    SNIFF_SUBRATING_RES, PAUSE_ENCRYPTION_REQ, RESUME_ENCRYPTION_REQ, IO_CAPABILITY_REQ,
    IO_CAPABILITY_RES, NUMERIC_COMPARISON_FAILED, PASSKEY_FAILED, OOB_FAILED,
    KEYPRESS_NOTIFICATION, POWER_CONTROL_REQ, POWER_CONTROL_RES,
};

#endif
