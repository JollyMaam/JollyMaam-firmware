#ifndef CYCLONE2_USB_PROTOCOL_H
#define CYCLONE2_USB_PROTOCOL_H

/* Payload carried by the SDK's unnumbered, 64-byte custom HID reports. */
#define CYCLONE2_USB_PACKET_SIZE       64U
#define CYCLONE2_USB_MAGIC_SIZE         8U
#define CYCLONE2_USB_COMMAND_OFFSET     8U
#define CYCLONE2_USB_INVERSE_OFFSET     9U
#define CYCLONE2_USB_COMMAND_UBOOT   0x01U
#define CYCLONE2_USB_COMMAND_STATUS  0x02U
#define CYCLONE2_USB_DATA_OFFSET       12U
#define CYCLONE2_USB_RESPONSE_BIT    0x80U
#define CYCLONE2_USB_MAGIC_INITIALIZER \
    {'C', '2', 'C', 'F', 'G', 1U, 0xa5U, 0x5aU}

#endif
